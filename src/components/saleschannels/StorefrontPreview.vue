              <v-icon v-if="showsSearch && !searchField" size="13">search</v-icon>
              <v-icon v-if="!headerTools || headerTools.includes('account')" size="13">user-round</v-icon>
              <v-icon v-if="wishlist" size="13">heart</v-icon>
