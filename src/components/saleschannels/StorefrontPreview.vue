                <span class="sf-finder__part-row">
                  <span class="sf-finder__part-input">TQ-BRK-4471</span>
                  <span class="sf-finder__part-go"><v-icon size="11" aria-hidden="true">search</v-icon>Search</span>
                </span>
              </span>
            </span>
          </div>

